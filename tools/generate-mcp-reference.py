"""Generate the exposed-tool reference from the compiled, checked capability registry."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
DESTINATION = ROOT / 'docs/mcp/capabilities.md'


def validate(rows):
    names, methods = set(), set()
    for row in rows:
        assert row['name'] not in names and row['method'] not in methods, row['method']
        names.add(row['name'])
        methods.add(row['method'])
        contract = row['authoring']
        assert contract['task'] and contract['prerequisites'] and contract['historyScope'], row['method']
        for reference in [contract['owner'], *contract['verification']['checks']]:
            path = (ROOT / reference).resolve()
            assert path.is_relative_to(ROOT) and path.is_file(), reference
        assert row['inputSchema']['type'] == 'object'
        assert row['inputSchema']['additionalProperties'] is False
        if row.get('outputSchema') is not None:
            assert row['outputSchema']['type'] == 'object'
            assert row['outputSchema']['additionalProperties'] is False
            assert row['outputSchema']['required']
        assert contract['verification']['limitation']


def render(rows):
    lines = ['# MCP exposed-tool reference', '',
             'Generated by `tools/generate-mcp-reference.py` from the compiled capability registry.', '',
             'This lists exposed adapter tools. Project lifecycle, change-set and collaboration controls',
             'are described in the [authoring guide](README.md). Complete native task coverage,',
             'typed output schemas and final certification remain open. A defined regression names',
             'a check to run; it does not claim a current passing receipt or runtime behavior.', '',
             'Read `providence://authoring/capabilities` for the complete machine-readable input',
             'schemas, mutation flags, prerequisites, ownership and verification scope.', '']
    declared = sum(isinstance(row.get('outputSchema'), dict) for row in rows)
    lines.extend([f'Success output schemas are advertised for {declared} of {len(rows)} registered routes.',
                  'This count excludes lifecycle controls and does not measure author-task completion.', ''])
    tasks = {}
    for row in rows:
        tasks.setdefault(row['authoring']['task'], []).append(row)
    for task, tools in sorted(tasks.items()):
        lines.extend(['## ' + task, '', '| Tool | Native command | Effect / history | Output schema | Defined MCP regression |',
                      '|---|---|---|---|---|'])
        for tool in sorted(tools, key=lambda row: row['method']):
            contract = tool['authoring']
            coverage = contract['verification']['status']
            scope = contract['historyScope']
            output = 'advertised' if tool.get('outputSchema') else 'pending'
            lines.append(f"| `{tool['name']}` | `{tool['method']}` | {scope} | {output} | {coverage} |")
        owners = sorted({row['authoring']['owner'] for row in tools})
        lines.extend(['', 'Native ownership: ' + ', '.join(f'`{owner}`' for owner in owners) + '.', '',
                      tools[0]['authoring']['prerequisites'][1] + '.', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mcp', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    process = subprocess.run([str(args.mcp), 'capability-registry'], check=True,
                             capture_output=True, text=True, encoding='utf-8', timeout=15)
    rows = json.loads(process.stdout)
    validate(rows)
    content = render(rows)
    if args.write:
        DESTINATION.write_text(content, encoding='utf-8')
    else:
        assert DESTINATION.read_text(encoding='utf-8') == content, 'Rebuild MCP and regenerate its reference with --write.'
    print(f'PROVIDENCE_MCP_REFERENCE_OK {len(rows)} exposed routes; native task completion remains separate')


if __name__ == '__main__':
    main()
